CREATE TABLE APP.USER_SESSION
(
    SESSION_ID UNIQUEIDENTIFIER NOT NULL,

    USER_ID BIGINT NOT NULL,

    LOGIN_TSTMP DATETIME2 NOT NULL,

    LOGOUT_TSTMP DATETIME2 NULL,

    SESSION_STATUS_CD VARCHAR(20) NOT NULL,

    IP_ADDRESS_TXT VARCHAR(50) NULL,

    USER_AGENT_TXT VARCHAR(1000) NULL,

    EXPIRES_TSTMP DATETIME2 NOT NULL,

    CREATED_TSTMP DATETIME2 NOT NULL,

    CREATED_BY VARCHAR(100) NOT NULL,

    UPDATED_TSTMP DATETIME2 NULL,

    UPDATED_BY VARCHAR(100) NULL,

    CONSTRAINT PK_USER_SESSION
        PRIMARY KEY CLUSTERED (SESSION_ID),

    CONSTRAINT FK_USER_SESSION_USER
        FOREIGN KEY (USER_ID)
        REFERENCES APP.[USER](USER_ID),



    CONSTRAINT CK_USER_SESSION_STATUS
        CHECK
        (
            SESSION_STATUS_CD IN
            (
                'ACTIVE',
                'LOGGED_OUT',
                'EXPIRED',
                'REVOKED'
            )
        )
);
GO

